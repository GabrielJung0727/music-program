function applyI18n() {
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (I18N[lang][key]) el.textContent = I18N[lang][key];
  });
}

function initCarousel() {
  const root = document.querySelector(".carousel");
  if (!root) return;
  const slides = [...root.querySelectorAll(".slide")];
  const dots = [...root.querySelectorAll(".dots button")];
  let i = 0;
  const show = (n) => {
    i = (n + slides.length) % slides.length;
    slides.forEach((s, idx) => s.classList.toggle("active", idx === i));
    dots.forEach((d, idx) => d.classList.toggle("on", idx === i));
  };
  root.querySelector(".prev")?.addEventListener("click", () => show(i - 1));
  root.querySelector(".next")?.addEventListener("click", () => show(i + 1));
  dots.forEach((d, idx) => d.addEventListener("click", () => show(idx)));
  setInterval(() => show(i + 1), 6000);
}

document.addEventListener("DOMContentLoaded", () => {
  document.body.insertAdjacentHTML("afterbegin", headerHTML());
  document.body.insertAdjacentHTML("beforeend", footerHTML() + promoHTML());
  applyI18n();
  initCarousel();

  document.getElementById("menuToggle")?.addEventListener("click", () => {
    document.getElementById("nav")?.classList.toggle("open");
  });

  document.getElementById("langSelect")?.addEventListener("change", (e) => {
    lang = e.target.value;
    localStorage.setItem("mono-lang", lang);
    location.reload();
  });
});
